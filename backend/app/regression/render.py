"""Plan -> Playwright Test (TypeScript). Deterministic: the same plan always
gives the same code, every string is escaped as a JSON string literal (valid
TypeScript), and comments are kept to one line, so nothing in a recorded value
or an AI reason can break out of the code."""
import json
import re
from urllib.parse import urlsplit

from app.regression.plan import is_same_origin


def ts(value) -> str:
    """A TypeScript string literal (JSON string syntax is valid TS)."""
    return json.dumps("" if value is None else str(value), ensure_ascii=False)


def comment(text: str | None) -> str:
    return " ".join(str(text or "").split())


def locator(loc: dict) -> str:
    m = loc.get("method")
    if m == "role":
        name = loc.get("name")
        return f"page.getByRole({ts(loc.get('role'))}" + (f", {{ name: {ts(name)}, exact: true }})" if name else ")")
    if m == "label":
        return f"page.getByLabel({ts(loc.get('value'))}, {{ exact: true }})"
    if m == "placeholder":
        return f"page.getByPlaceholder({ts(loc.get('value'))}, {{ exact: true }})"
    if m == "text":
        return f"page.getByText({ts(loc.get('value'))}, {{ exact: true }})"
    if m == "testid":
        return f"page.getByTestId({ts(loc.get('value'))})"
    return f"page.locator({ts(loc.get('value'))})"


def goto_target(url: str, base_url: str | None) -> str:
    if base_url and is_same_origin(url, base_url):
        parts = urlsplit(url)
        path = (parts.path or "/") + (f"?{parts.query}" if parts.query else "") + (f"#{parts.fragment}" if parts.fragment else "")
        return f"BASE_URL + {ts(path)}"
    return ts(url)


def action_line(a: dict) -> list[str]:
    target = locator(a.get("locator") or {})
    act = a.get("action")
    lines = []
    if a.get("in_frame"):
        lines.append("// Review: this happened inside a frame; it may need page.frameLocator(...).")
    if act == "click":
        lines.append(f"await {target}.click()")
    elif act == "dblclick":
        lines.append(f"await {target}.dblclick()")
    elif act == "fill" and a.get("masked"):
        secret = re.sub(r"[^A-Z0-9_]", "_", str(a.get("secret") or "MIRMERA_SECRET_VALUE").upper())
        lines.append(f"// Not recorded (sensitive). Set {secret} when running the test.")
        lines.append(f"await {target}.fill(process.env.{secret} ?? '')")
    elif act == "fill":
        lines.append(f"await {target}.fill({ts(a.get('value'))})")
    elif act == "select":
        lines.append(f"await {target}.selectOption({ts(a.get('value'))})")
    elif act in ("check", "uncheck"):
        lines.append(f"await {target}.{act}()")
    elif act == "press":
        lines.append(f"await {target}.press({ts(a.get('key') or 'Enter')})")
    elif act == "upload":
        # test.info().file works in CommonJS and ES-module projects alike (__dirname does not exist in ESM).
        files = ", ".join(f"path.join(path.dirname(test.info().file), 'fixtures', {ts(f)})" for f in (a.get("files") or ["file"]))
        lines.append("// Put the uploaded file(s) next to this test in a fixtures/ folder.")
        lines.append(f"await {target}.setInputFiles([{files}])")
    return lines


def assertion_lines(a: dict) -> list[str]:
    why = ts(comment(a.get("why")))
    kind = a["kind"]
    if kind == "visible":
        return [f"await expect({locator(a['locator'])}, {why}).toBeVisible()"]
    if kind == "hidden":
        return [f"await expect({locator(a['locator'])}, {why}).toBeHidden()"]
    if kind == "text":
        return [f"await expect({locator(a['locator'])}, {why}).toContainText({ts(a['expected'])})"]
    if kind == "value":
        return [f"await expect({locator(a['locator'])}, {why}).toHaveValue({ts(a['expected'])})"]
    if kind == "url":
        return [f"await expect.poll(() => page.url(), {{ message: {why} }}).toContain({ts(a['expected'])})"]
    if kind == "no_console_errors":
        return [f"expect(consoleErrors, {why}).toEqual([])"]
    if kind == "no_page_errors":
        return [f"expect(pageErrors, {why}).toEqual([])"]
    if kind == "no_failed_requests":
        part = a.get("url_contains") or ""
        return [f"expect(failedRequests.filter((r) => r.includes({ts(part)})), {why}).toEqual([])"]
    return []


def render(plan: dict, *, bug_title: str, oracle: str, issue_links: list[str],
           provenance: str, known_failing: bool) -> str:
    base_url = plan.get("base_url")
    steps, assertions = plan["steps"], plan["assertions"]
    kinds = {a["kind"] for a in assertions}
    needs_path = any(s.get("action", {}).get("action") == "upload" for s in steps)

    out = [f"// Regression test for: {comment(bug_title)}"]
    if issue_links:
        out.append(f"// Issue: {comment(', '.join(issue_links))}")
    out.append(f"// Oracle: {comment(oracle)}")
    out.append(f"// Generated by Mirmera ({comment(provenance)}) from actions recorded in an exploratory session.")
    if plan.get("assumptions"):
        out.append("// Assumptions to check before committing:")
        out += [f"//  - {comment(x)}" for x in plan["assumptions"]]
    out.append("import { test, expect } from '@playwright/test'")
    if needs_path:
        out.append("import path from 'path'")
    out.append("")
    out.append(f"const BASE_URL = process.env.BASE_URL ?? {ts(base_url or 'http://localhost:3000')}")
    out.append("")
    out.append(f"test({ts(plan.get('title') or bug_title)}, async ({{ page }}) => {{")
    body: list[str] = []
    if known_failing:
        body.append(f"test.fail(true, {ts('Known bug: ' + comment(', '.join(issue_links) or bug_title) + '. Remove this line once it is fixed.')})")
        body.append("")
    if "no_console_errors" in kinds:
        body += ["const consoleErrors: string[] = []",
                 "page.on('console', (m) => {",
                 "  if (m.type() === 'error' && !m.text().startsWith('Failed to load resource')) consoleErrors.push(m.text())",
                 "})"]
    if "no_page_errors" in kinds:
        body += ["const pageErrors: string[] = []",
                 "page.on('pageerror', (e) => pageErrors.push(e.message))"]
    if "no_failed_requests" in kinds:
        body += ["const failedRequests: string[] = []",
                 "page.on('response', (r) => { if (r.status() >= 400) failedRequests.push(`${r.request().method()} ${r.url()} -> ${r.status()}`) })",
                 "page.on('requestfailed', (r) => { if (!r.failure()?.errorText.includes('ERR_ABORTED')) failedRequests.push(`${r.method()} ${r.url()} -> ${r.failure()?.errorText}`) })"]
    if kinds & {"no_console_errors", "no_page_errors", "no_failed_requests"}:
        body.append("")

    for n, step in enumerate(steps, 1):
        label = step.get("why") or ("Open the page" if step["type"] == "goto" else step["action"].get("summary", ""))
        body.append(f"// {n}. {comment(label)}")
        if step["type"] == "goto":
            body.append(f"await page.goto({goto_target(step['url'], base_url)})")
        else:
            body += action_line(step["action"])

    body.append("")
    if kinds & {"no_console_errors", "no_page_errors", "no_failed_requests"}:
        body.append("await page.waitForLoadState('networkidle').catch(() => {})  // let requests settle")
    body.append("// What should happen (the oracle). These fail while the bug exists.")
    for a in assertions:
        body += assertion_lines(a)

    out += [("  " + line) if line else "" for line in body]
    out.append("})")
    return "\n".join(out) + "\n"
