import { API_URL, expect, test } from './fixtures'

test('accounts: another account sees nothing of this workspace; tokens and workspaces on the Account page', async ({ page, api, browser }) => {
  const project = await api.newProject('AddisVerify Accounts')

  await test.step('a second person signs up in their own browser: an empty workspace, and our project is closed to them', async () => {
    const other = await browser.newContext({ storageState: { cookies: [], origins: [] } })
    const p = await other.newPage()
    await p.goto(`/projects/${project.id}/dashboard`)
    await expect(p).toHaveURL(/\/signin\?next=/)
    await p.getByRole('button', { name: 'Create an account' }).click()
    await p.getByLabel('Your name').fill('Sara')
    await p.getByLabel('Email').fill('sara@other.test')
    await p.getByLabel('Password').fill('another long passphrase')
    await p.getByLabel('Workspace (your team or company)').fill('Other Co')
    await p.getByRole('button', { name: 'Create account' }).click()
    await expect(p.getByText("This project doesn't exist, or it's in a workspace you're not a member of.")).toBeVisible()
    await p.getByRole('link', { name: 'See your projects' }).click()
    await expect(p.getByText('No projects yet. Create one to start testing.')).toBeVisible()
    await expect(p.getByRole('link', { name: 'Mirmera home' })).toContainText('Other Co')
    await other.close()
  })

  await test.step('the Account page: an extension token is shown once', async () => {
    await page.goto('/projects')
    await page.getByRole('link', { name: 'Account', exact: true }).click()
    await expect(page.getByRole('region', { name: 'Profile' })).toContainText('attu@e2e.test')
    const tokens = page.getByRole('region', { name: 'Chrome extension' })
    await tokens.getByLabel('Token label').fill('Chrome on my laptop')
    await tokens.getByRole('button', { name: 'Create token' }).click()
    const token = await tokens.getByLabel('Token', { exact: true }).inputValue()
    expect(token).toMatch(/^mm_/)
    expect((await (await page.request.get(`${API_URL}/auth/me`, { headers: { Authorization: `Bearer ${token}` } })).json()).user.email).toBe('attu@e2e.test')
    await expect(tokens.getByRole('list', { name: 'Extension tokens' })).toContainText('Chrome on my laptop')
  })

  await test.step('a second workspace: switch to it and its projects are empty', async () => {
    const ws = page.getByRole('region', { name: 'Workspaces' })
    await ws.getByLabel('New workspace name').fill('Client B')
    await ws.getByRole('button', { name: 'New workspace' }).click()
    await expect(ws.getByRole('list', { name: 'Your workspaces' })).toContainText('Client B · current')
    await page.getByRole('link', { name: 'Mirmera home' }).click()
    await expect(page.getByText('No projects yet. Create one to start testing.')).toBeVisible()
    await page.getByLabel('Workspace', { exact: true }).selectOption({ label: 'AddisVerify' })
    await expect(page.getByRole('link', { name: 'AddisVerify Accounts' })).toBeVisible()
  })

  await test.step('sign in and out in another browser (signing out here would sign out the other specs)', async () => {
    const laptop = await browser.newContext({ storageState: { cookies: [], origins: [] } })
    const p = await laptop.newPage()
    await p.goto('/projects')
    await p.getByLabel('Email').fill('attu@e2e.test')
    await p.getByLabel('Password').fill('not my password at all')
    await p.getByRole('button', { name: 'Sign in' }).click()
    await expect(p.getByRole('alert')).toContainText("That email and password don't match an account.")
    await p.getByLabel('Password').fill('correct horse battery')
    await p.getByRole('button', { name: 'Sign in' }).click()
    await expect(p.getByRole('heading', { name: 'Projects' })).toBeVisible()
    await p.getByRole('link', { name: 'Account', exact: true }).click()
    await p.getByRole('button', { name: 'Sign out' }).click()
    await expect(p.getByRole('heading', { name: 'Sign in' })).toBeVisible()
    await p.goto('/projects')
    await expect(p).toHaveURL(/\/signin/)
    await laptop.close()
  })
})
